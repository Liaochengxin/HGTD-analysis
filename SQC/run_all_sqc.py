#!/usr/bin/env python3
"""Build and run the SQC sensor plan from one YAML configuration.

Usage:
    run_all_sqc.py CONFIG [--dry-run]

Local mode executes the plan sequentially and does not initialize ATLAS.
Cluster jobs are generated by make_condor_jobs.py from the same plan helpers.
"""

import argparse
import csv
from functools import lru_cache
import re
import subprocess
import time
from pathlib import Path

import yaml

from collect_results import collect_summary


def load_wafer_temps(path):
    """Map the exact CQC wafer serial number to its measured temperature."""
    temps = {}
    with path.open(errors="ignore", newline="") as fh:
        for row in csv.reader(fh):
            if len(row) < 2 or not row[0].strip().startswith("20WS"):
                continue
            try:
                temps[row[0].strip()] = float(row[1].strip())
            except ValueError:
                continue
    return temps


@lru_cache(maxsize=8)
def first_curve_template(root_name, pattern):
    """Cache the first available CQC curve template to avoid rescanning EOS."""
    root = Path(root_name)
    if not root.is_dir():
        return None, None
    for directory in sorted(root.glob(pattern)):
        if not directory.is_dir():
            continue
        files = sorted(directory.glob("*-1.csv"))
        if files:
            prefix = files[0].name[:-len("-1.csv")]
            return str(directory / prefix) + "-%d.csv", directory.name
    return None, None


def find_cqc(cqc_root, cqc_sample, batch, wafer, pos, temps=None):
    """Return (probe-card CSV template, temperature, match source)."""
    sensor_serial = f"20WS2{batch:03d}{wafer:04d}{pos:02d}"
    wafer_dir = cqc_sample / f"B{batch}_{wafer}"
    if wafer_dir.is_dir():
        data_dirs = sorted(
            d for d in wafer_dir.iterdir()
            if d.is_dir() and d.name.startswith("20WS")
        )
        if data_dirs and (data_dirs[0] / f"{sensor_serial}-1.csv").exists():
            tp = temps.get(data_dirs[0].name) if temps is not None else None
            return str(data_dirs[0] / sensor_serial) + "-%d.csv", tp, f"matched:{wafer_dir.name}"

    if cqc_root.exists():
        for directory in sorted(p for p in cqc_root.iterdir() if p.is_dir()):
            if (directory / f"{sensor_serial}-1.csv").exists():
                tp = temps.get(directory.name) if temps is not None else None
                return str(directory / sensor_serial) + "-%d.csv", tp, "matched:fallback"

        template, serial = first_curve_template(str(cqc_root), "*")
        if template:
            tp = temps.get(serial) if temps is not None else None
            return template, tp, "placeholder:fallback"

    template, serial = first_curve_template(str(cqc_sample), "B*/20WS*")
    if template:
        tp = temps.get(serial) if temps is not None else None
        return template, tp, "placeholder:cqc-folder"
    return None, None, "missing"


def discover(sqc_root):
    """Return sensor inputs directly under one selected SQC batch directory."""
    sensors = []
    batch_match = re.fullmatch(r"([12])(?:st|nd)_batch_SQC", sqc_root.name)
    if not batch_match:
        raise SystemExit(
            f"sqc_folder must point to a batch directory named "
            f"1st_batch_SQC or 2nd_batch_SQC: {sqc_root}"
        )
    generation = "1st" if batch_match.group(1) == "1" else "2nd"
    for sensor_dir in sorted(sqc_root.glob("B*/W*_P*/SweepVoltage0")):
        match = re.fullmatch(r"W(\d+)_P(\d+)", sensor_dir.parent.name)
        if not match:
            continue
        wafer, pos = int(match.group(1)), int(match.group(2))
        batch_name = sensor_dir.parent.parent.name
        if not batch_name.startswith("B"):
            continue
        try:
            batch = int(batch_name[1:])
        except ValueError:
            continue
        label = f"{generation}-B{batch:02d}-W{wafer:02d}-P{pos}"
        sensors.append((label, batch, wafer, pos, sensor_dir))
    return sensors


def build_plan(cfg):
    """Resolve sensor inputs and CQC matches once for local and batch modes."""
    main_path = Path(cfg["main_path"])
    sqc_root = main_path / cfg["sqc_folder"]
    cqc_fallback = main_path / cfg.get("cqc_fallback_folder", "")
    cqc_sample = main_path / cfg["cqc_folder"]
    temperature_file = main_path / cfg["temp_file"]
    output_root = main_path / cfg["output_path"]
    if not sqc_root.is_dir():
        raise SystemExit(f"SQC data root not found: {sqc_root}")
    if not temperature_file.is_file():
        raise SystemExit(f"CQC temperature file not found: {temperature_file}")
    temps = load_wafer_temps(temperature_file)
    tn = float(cfg.get("tn", 20.0))

    sensors = discover(sqc_root)
    if not sensors:
        raise SystemExit(
            f"no sensor inputs found under {sqc_root}; "
            "expected Bxx/Wx_Py/SweepVoltage0 directly under sqc_folder"
        )

    plan = []
    for label, batch, wafer, pos, needle_dir in sensors:
        probe_tpl, tp, source = find_cqc(cqc_fallback, cqc_sample, batch, wafer, pos, temps)
        if probe_tpl is None:
            print(f"  [skip] {label}: no CQC input found")
            continue
        if tp is None:
            tp = 20.0
            print(f"  [warn] {label}: no temperature for matched CQC data; using Tp=20.0°C")
        n_files = len(list(needle_dir.glob("1-*.csv")))
        if n_files == 0:
            print(f"  [skip] {label}: needle directory is empty")
            continue
        if n_files != 225:
            print(f"  [warn] {label}: found {n_files}/225 needle CSVs")
        if source.startswith("placeholder"):
            print(f"  [warn] {label}: using CQC placeholder data ({source})")
        output_group = f"B{batch:02d}"
        output_sensor = f"W{wafer:02d}-P{pos}"
        output_dir = output_root / output_group / output_sensor
        plan.append({
            "label": label,
            "output_group": output_group,
            "output_sensor": output_sensor,
            "tp": tp,
            "tn": tn,
            "probe_tpl": probe_tpl,
            "needle_tpl": str(needle_dir / "1-%d.csv"),
            "source": source,
            "output_root": output_root,
            "output_dir": output_dir,
        })
        print(f"  {label}: Tp={tp} ({source}), output={output_dir}")
    return plan


def macro_call(macro, task):
    return (f'{macro}({task["tp"]},{task["tn"]},'
            f'"{task["probe_tpl"]}","{task["needle_tpl"]}",'
            f'"{task["output_dir"]}/")')


def write_plan_manifest(plan, output_root):
    output_root.mkdir(parents=True, exist_ok=True)
    path = output_root / "sensor_plan.csv"
    with path.open("w", newline="") as fh:
        writer = csv.DictWriter(
            fh, fieldnames=["label", "output_group", "output_sensor", "Tp", "Tn", "cqc"]
        )
        writer.writeheader()
        for task in plan:
            writer.writerow({"label": task["label"],
                             "output_group": task["output_group"],
                             "output_sensor": task["output_sensor"],
                             "Tp": task["tp"],
                             "Tn": task["tn"], "cqc": task["source"]})
    return path


def run_local(plan, macro):
    start = time.time()
    succeeded = 0
    output_root = plan[0]["output_root"]
    write_plan_manifest(plan, output_root)
    for index, task in enumerate(plan, 1):
        task["output_dir"].mkdir(parents=True, exist_ok=True)
        log = task["output_dir"] / "run.log"
        print(f"\n[{index}/{len(plan)}] {task['label']}", flush=True)
        with log.open("w") as fh:
            proc = subprocess.run(
                ["root", "-b", "-q", macro_call(macro, task)],
                stdout=fh, stderr=subprocess.STDOUT,
            )
        if proc.returncode:
            print(f"  FAILED (exit {proc.returncode}); see {log}")
        else:
            succeeded += 1
    collect_summary(output_root)
    print(f"Finished: {succeeded}/{len(plan)} sensors in {time.time()-start:.0f}s")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("config")
    parser.add_argument("--dry-run", action="store_true", help="print the plan only")
    args = parser.parse_args()

    with Path(args.config).open() as fh:
        cfg = yaml.safe_load(fh)
    plan = build_plan(cfg)
    print(f"Plan: {len(plan)} sensor jobs")
    if args.dry_run:
        print("Dry run; no ROOT jobs executed.")
        return
    if not plan:
        raise SystemExit("no runnable sensors in plan")
    macro = str(Path(cfg["main_path"]) / cfg["macro"])
    run_local(plan, macro)


if __name__ == "__main__":
    main()
